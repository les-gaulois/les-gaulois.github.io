import { describe, expect, it } from "vitest";
import { commandeIsolee, dossierDeCarte, FicheDePartie, fichiersDeCarte, fichiersDeLaPartie, IMAGE_DU_MOTEUR, lirePassage, MOTIFS_DU_MOTEUR, noticeDesCartes, verrouDuMoteur } from "../../src/lib/rejeu-openfront";

/** Un extrait du fichier où le jeu nomme ses cartes, dans sa forme. */
const NOMS = `// Code generated by map-generator; DO NOT EDIT.
export enum GameMapType {
  FourIslands = "Four Islands", // map-generator/assets/maps/fourislands/info.json
  GatewayToTheAtlantic = "Gateway to the Atlantic", // map-generator/assets/maps/gatewaytotheatlantic/info.json
  SoutheastAsia = "SoutheastAsia", // map-generator/assets/maps/southeastasia/info.json
  World = "World",
}`;

describe("dossierDeCarte", () => {
  it("donne le dossier d'une carte comme le serveur du jeu : le nom de sa constante, en minuscules", () => {
    expect(dossierDeCarte(NOMS, "Four Islands")).toBe("fourislands");
    expect(dossierDeCarte(NOMS, "Gateway to the Atlantic")).toBe("gatewaytotheatlantic");
    expect(dossierDeCarte(NOMS, "SoutheastAsia")).toBe("southeastasia");
    expect(dossierDeCarte(NOMS, "World")).toBe("world");
  });
  it("une carte absente ne donne rien : le nom se déduit alors autrement", () => {
    expect(dossierDeCarte(NOMS, "Atlantis")).toBeNull();
    expect(dossierDeCarte("", "World")).toBeNull();
  });
});

describe("verrouDuMoteur", () => {
  const entree = (nom: string, version: string, extra: object = {}) => ({
    version,
    resolved: `https://registry.npmjs.org/${nom}/-/x-${version}.tgz`,
    integrity: `sha512-${nom.replace(/[^a-z]/g, "").repeat(4)}==`,
    ...extra,
  });
  const verrou = JSON.stringify({
    packages: {
      "": { name: "openfront" },
      "node_modules/zod": entree("zod", "4.4.2"),
      "node_modules/nanoid": entree("nanoid", "5.1.16", { dependencies: { petit: "^2" } }),
      "node_modules/petit": entree("petit", "1.0.0"),
      "node_modules/nanoid/node_modules/petit": entree("petit", "2.0.0", { optionalDependencies: { absent: "1" } }),
      "node_modules/@openfront/engine": { link: true, resolved: "packages/engine" },
      "node_modules/vite": entree("vite", "7.0.0"),
    },
  });
  const paquets = [JSON.stringify({ dependencies: { "@openfront/engine-api": "0.0.0", zod: "^4.4.2" } }), JSON.stringify({ dependencies: { nanoid: "^5", zod: "^4" } }), JSON.stringify({ name: "sans dépendances" })];
  it("prend les bibliothèques du moteur et les leurs, à leur place dans le verrou du jeu, avec leur empreinte, et rien d'autre", () => {
    const { noms, paquet, verrou: petit } = verrouDuMoteur(paquets, verrou);
    expect(noms).toEqual(["nanoid", "zod"]);
    expect(paquet).toEqual({ name: "moteur-openfront", version: "0.0.0", dependencies: { nanoid: "5.1.16", zod: "4.4.2" }, private: true });
    const entrees = (petit as { packages: Record<string, { version?: string; integrity?: string }> }).packages;
    // Comme Node : la version rangée sous nanoid passe avant celle du dessus ; ni vite ni le moteur du jeu n'y sont.
    expect(Object.keys(entrees)).toEqual(["", "node_modules/nanoid", "node_modules/nanoid/node_modules/petit", "node_modules/zod"]);
    expect(entrees["node_modules/zod"]?.integrity).toMatch(/^sha512-/);
    expect(petit).toMatchObject({ lockfileVersion: 3, requires: true });
  });
  it("refuse une bibliothèque absente du verrou, sans empreinte, venue d'ailleurs que du registre de npm, ou au nom étrange", () => {
    expect(() => verrouDuMoteur([JSON.stringify({ dependencies: { jose: "^6" } })], verrou)).toThrow("jose");
    expect(() => verrouDuMoteur([JSON.stringify({ dependencies: { "zod; rm -rf": "1" } })], verrou)).toThrow();
    const seul = (e: object) => JSON.stringify({ packages: { "node_modules/zod": e } });
    const zod = [JSON.stringify({ dependencies: { zod: "^4" } })];
    expect(() => verrouDuMoteur(zod, seul({ version: "4.4.2", resolved: "https://registry.npmjs.org/zod/-/zod-4.4.2.tgz" }))).toThrow("format inattendu");
    expect(() => verrouDuMoteur(zod, seul(entree("zod", "4.4.2", { resolved: "https://exemple.test/zod.tgz" })))).toThrow("format inattendu");
    expect(() => verrouDuMoteur(zod, seul(entree("zod", "latest && echo")))).toThrow("format inattendu");
  });
});

describe("FicheDePartie", () => {
  const fiche = { gitCommit: "8b5d071eed95f07c701b32e4c64e95b03f8577c1", info: { gameID: "cWUM8LDDxH", config: { gameMap: "Four Islands", gameMapSize: "Normal" }, num_turns: 14341 }, turns: [{ turnNumber: 0, intents: [] }] };
  it("ne vérifie que ce que le rejeu utilise", () => {
    expect(FicheDePartie.parse(fiche).info.config.gameMapSize).toBe("Normal");
  });
  it("refuse un commit qui n'en est pas un, une taille de carte inconnue, une partie sans étapes", () => {
    expect(() => FicheDePartie.parse({ ...fiche, gitCommit: "main" })).toThrow();
    expect(() => FicheDePartie.parse({ ...fiche, info: { ...fiche.info, config: { ...fiche.info.config, gameMapSize: "Huge" } } })).toThrow();
    expect(() => FicheDePartie.parse({ ...fiche, turns: [] })).toThrow();
    expect(() => FicheDePartie.parse({ ...fiche, info: { ...fiche.info, gameID: "../x" } })).toThrow();
  });
  it("lit les fichiers de la carte que le moteur lit, selon la taille de la partie", () => {
    expect(fichiersDeCarte("Normal")).toEqual(["manifest.json", "map.bin", "map4x.bin"]);
    expect(fichiersDeCarte("Compact")).toEqual(["manifest.json", "map4x.bin", "map16x.bin"]);
  });
  it("ne prend du dépôt du jeu que le code du moteur, ni le client, ni les cartes, ni ce qui est propriétaire", () => {
    expect(MOTIFS_DU_MOTEUR.join(" ")).not.toMatch(/proprietary|src\/client|resources\/maps/);
  });
});

describe("le passage du rejeu", () => {
  it("relit la liste des parties vues ; sans liste lisible, ou si le rejeu s'est arrêté en route, rien n'attend", () => {
    expect(lirePassage(JSON.stringify({ format: 1, fini: true, vues: ["a1", "b2"] }))).toEqual(new Set(["a1", "b2"]));
    expect(lirePassage(JSON.stringify({ format: 1, fini: false, vues: ["a1"] }))).toBeNull();
    expect(lirePassage(null)).toBeNull();
    expect(lirePassage("{")).toBeNull();
    expect(lirePassage(JSON.stringify({ format: 1, fini: true, vues: ["../x"] }))).toBeNull();
    expect(lirePassage(JSON.stringify({ format: 1, vues: [] }))).toBeNull();
  });
  it("ne fait un nom de fichier que d'un identifiant de partie sûr", () => {
    expect(fichiersDeLaPartie("cWUM8LDDxH")).toEqual({ meta: ".cache/cartes-finales/cWUM8LDDxH.json", cases: ".cache/cartes-finales/cWUM8LDDxH.bin.gz" });
    expect(fichiersDeLaPartie("../passage")).toBeNull();
    expect(fichiersDeLaPartie("")).toBeNull();
  });
});

describe("l'isolement du moteur", () => {
  const args = commandeIsolee({ moteur: "/w/m.mjs", fiche: "/w/f.json", carte: "/w/carte", sortie: "/w/sortie" }, "rejeu-x");
  it("le lance dans un conteneur sans réseau, sans droits, en lecture seule, d'une image fixée par son empreinte", () => {
    for (const option of ["run", "--rm", "--network=none", "--read-only", "--cap-drop=ALL", "--security-opt=no-new-privileges", "--user=65534:65534"]) expect(args).toContain(option);
    expect(IMAGE_DU_MOTEUR).toMatch(/^node:22[\w.-]*@sha256:[0-9a-f]{64}$/);
    expect(args).toContain(IMAGE_DU_MOTEUR);
  });
  it("ne lui montre que le moteur, la fiche et la carte en lecture, et un dossier de sortie, sans aucune variable du job", () => {
    expect(args.filter((a) => a.startsWith("--volume="))).toEqual(["--volume=/w/m.mjs:/rejeu/moteur.mjs:ro", "--volume=/w/f.json:/rejeu/fiche.json:ro", "--volume=/w/carte:/rejeu/carte:ro", "--volume=/w/sortie:/rejeu/sortie"]);
    expect(args.some((a) => /^(-e$|--env|--privileged|--network=host|--pid=|--ipc=|--userns=host)/.test(a))).toBe(false);
  });
});

describe("la notice des cartes de fin", () => {
  it("dit d'où vient le terrain, sous quelle licence, et ce qui a changé", () => {
    const notice = noticeDesCartes(["8b5d071eed95f07c701b32e4c64e95b03f8577c1"], "2026-11-15");
    for (const attendu of ["© OpenFront and Contributors", "CC BY-SA 4.0", "https://creativecommons.org/licenses/by-sa/4.0/", "https://github.com/openfrontio/OpenFrontIO", "8b5d071eed95f07c701b32e4c64e95b03f8577c1", "Modifié le 2026-11-15"]) {
      expect(notice).toContain(attendu);
    }
  });
});
